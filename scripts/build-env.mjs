// Builds dist/agent-spaghetti-env.mjs (or the path given as the first argument): one file, runs on Node >= 20 inside WSL distros (no TypeScript needed there).
import { build } from 'esbuild';
const out = process.argv[2] ?? 'dist/agent-spaghetti-env.mjs';
await build({
  entryPoints: ['packages/env/src/main.ts'], outfile: out, bundle: true,
  platform: 'node', target: 'node20', format: 'esm', legalComments: 'none',
  banner: { js: '// agent-spaghetti-env (generated by scripts/build-env.mjs; do not edit)' },
  define: { 'import.meta.main': 'true' },
});
console.log(`built ${out}`);
