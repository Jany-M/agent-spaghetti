// Builds everything that does not run from TypeScript sources:
//   <out>/agent-spaghetti-env.mjs   the program that runs inside WSL distros (Node >= 20, one file)
//   <out>/app/                      the tray (Electron main + preload, sandboxed renderer, popover page, assets)
// Usage: node scripts/build.mjs [outDir]   (default: dist)
import { build } from 'esbuild';
import { cpSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CSS } from '../packages/ui/src/styles.ts';
import { pngToIco } from '../packages/app/src/logic.ts';

const out = process.argv[2] ?? 'dist';
const banner = { js: '// generated by scripts/build.mjs; do not edit' };
const app = join(out, 'app');
mkdirSync(app, { recursive: true });
await Promise.all([
  build({ entryPoints: ['packages/env/src/main.ts'], outfile: join(out, 'agent-spaghetti-env.mjs'), bundle: true, platform: 'node', target: 'node20',
    format: 'esm', legalComments: 'none', banner, define: { 'import.meta.main': 'true' } }),
  ...['main', 'preload'].map(n => build({ entryPoints: [`packages/app/src/${n}.ts`], outfile: join(app, `${n}.cjs`), bundle: true, platform: 'node',
    format: 'cjs', external: ['electron'], legalComments: 'none', banner })),
  build({ entryPoints: ['packages/app/src/renderer.ts'], outfile: join(app, 'renderer.js'), bundle: true, platform: 'browser', format: 'iife',
    minify: true, legalComments: 'none', define: { 'process.env.NODE_ENV': '"production"' } }),
]);
cpSync('packages/app/src/popover.html', join(app, 'popover.html'));
cpSync('packages/app/assets', app, { recursive: true });
writeFileSync(join(app, 'popover.css'), CSS);
writeFileSync(join(app, 'icon.ico'), pngToIco(readFileSync('packages/app/assets/icon.png')));   // Windows shortcuts
console.log(`built ${out}/agent-spaghetti-env.mjs and ${out}/app`);
